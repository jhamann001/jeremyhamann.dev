// Writes custodian_library.py from the Transfer Tracker demo's custodian library, so both demos describe the same
// custodians. Run it from apps/statements after the tracker's library changes (Node 22.18+ reads the .ts file
// directly); tests/test_samples.py fails while the two disagree.
//
//   node tools/export_custodian_library.mjs
import { writeFileSync } from "node:fs";
import { CUSTODIAN_LIBRARY } from "../../acat/src/lib/demo/custodian-library.ts";

const rows = CUSTODIAN_LIBRARY.map((c) => ({
  name: c.name,
  transfer_type: c.transferType,
  dtc: c.dtc,
  signature: c.signature ?? null,
  medallion_required: c.medallionRequired ?? null,
  letter_of_acceptance: c.letterOfAcceptance ?? null,
  liquidation_method: c.liquidationMethod ?? null,
  return_method: c.returnMethod ?? null,
  watchouts: c.watchouts ?? null,
}));
const json = JSON.stringify(rows, null, 1);
if (json.includes('"""')) throw new Error("library text holds a triple quote; pick another Python quoting");

writeFileSync(
  new URL("../custodian_library.py", import.meta.url),
  `"""
The Transfer Tracker demo's custodian library (apps/acat/src/lib/demo/custodian-library.ts): every delivering firm
with its DTC number, transfer method and watch-outs. Real firms; no client names, examples or account numbers.

Generated by tools/export_custodian_library.mjs. Do not edit; change the tracker's library and run the script.
"""

import json

CUSTODIANS = json.loads(r"""${json}""")
`,
);
console.log(`custodian_library.py: ${rows.length} custodians`);
