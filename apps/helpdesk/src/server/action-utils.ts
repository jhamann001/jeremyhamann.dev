/**
 * `runAction` — the single wrapper every `src/server/*.actions.ts` export goes through
 * (shared convention 4).
 *
 * Order: `requireViewerOrThrow` (UNAUTHORIZED) → request context → handler. Errors never reach the
 * client as exceptions: ZodError → VALIDATION with field errors; ForbiddenError → an awaited
 * `AUTHZ_DENIED` row, then FORBIDDEN; other AppErrors → their code; anything else → INTERNAL with a
 * structured log line carrying the action name, the error's LABEL and its digest only (never its
 * message, which could contain ticket text).
 */
import { z } from "zod";
import type { ActionResult, RequestContext, Viewer } from "@/types/domain";
import { actorFromViewer, recordDenied } from "@/lib/audit";
import { ForbiddenError, isAppError, toActionError, UnauthorizedError } from "@/lib/errors";
import { logError } from "@/lib/logger";
import { getRequestContext } from "@/lib/request-context";
import { requireViewerOrThrow } from "@/lib/session";
import { zodToActionError } from "@/server/validation";

export type ActionHandler<T> = (viewer: Viewer, ctx: RequestContext) => Promise<T>;

function internalError(name: string, e: unknown): ActionResult<never> {
  // `digest` is Next's own opaque correlation id for a server-side throw — it is generated by the
  // framework, not derived from the caught error's message, so it stays a field. The error itself is
  // handed to `logError`, which records `errorLabel(e)` and nothing else: reading `e.name` here would
  // be the CWE-209 taint (security scanner) even though the label is the same string.
  const digest = typeof (e as { digest?: unknown } | null)?.digest === "string" ? (e as { digest: string }).digest : null;
  logError(`action:${name}`, e, { digest });
  return { ok: false, code: "INTERNAL", message: "Unexpected error" };
}

export async function runAction<T>(name: string, fn: ActionHandler<T>): Promise<ActionResult<T>> {
  let viewer: Viewer;
  try {
    viewer = await requireViewerOrThrow();
  } catch (e) {
    if (e instanceof UnauthorizedError) return toActionError(e);
    return internalError(name, e);
  }

  let ctx: RequestContext;
  try {
    ctx = await getRequestContext();
  } catch (e) {
    return internalError(name, e);
  }

  try {
    const data = await fn(viewer, ctx);
    return { ok: true, data };
  } catch (e) {
    if (e instanceof z.ZodError) return zodToActionError(e);
    if (e instanceof ForbiddenError) {
      // I3/I5: the denial is evidence; if it cannot be recorded the request fails rather than
      // returning a silent FORBIDDEN.
      try {
        await recordDenied(actorFromViewer(viewer), ctx, `${name}: ${e.message}`, e.ticketId);
      } catch (auditError) {
        return internalError(name, auditError);
      }
      return toActionError(e);
    }
    if (isAppError(e)) return toActionError(e);
    return internalError(name, e);
  }
}
